"""Acceptance tests for the vote maths, with the numbers from the brief (nu = 4).

Run with:  python -m unittest discover tests
"""
import math
import unittest

import votes

NU = 4
TAU = 240                                             # 4 minutes left
SD = 0.5 / math.sqrt(365 * 86400)                     # realised vol 50% a year, per sqrt-second
PCT = 100 * math.sqrt(TAU)                            # vote per sqrt-second -> width in % over the time left


def leg(name, line, mid, line_err):
    # no averaging adjustment (w = 0); bid = ask = mid
    return {"name": name, "spot": 100_000, "line": line, "bid": mid, "ask": mid, "tick": 0.01,
            "line_err": line_err, "tau": TAU, "w": 0}


LEGS = [leg("5m", 99_950, 0.62, 15), leg("15m", 100_200, 0.05, 15), leg("1h", 100_400, 0.03, 0)]


class BriefAcceptanceTest(unittest.TestCase):
    def setUp(self):
        self.votes = {l["name"]: votes.leg_vote(l, NU) for l in LEGS}
        self.anchor = votes.anchor_vote(SD, NU)

    def test_15m_q_and_vote(self):
        v = self.votes["15m"]
        self.assertAlmostEqual(v["q"], 2.1318, places=4)
        self.assertAlmostEqual(v["c"] * 100, 0.0937, places=4)

    def test_votes_and_error_bars(self):
        expected = {"5m": (0.153, 0.046), "15m": (0.094, 0.008), "1h": (0.154, 0.009)}
        for name, (c, sigma) in expected.items():
            # the brief rounds the 1h vote 0.1535 up to 0.154, so allow 0.0006
            self.assertAlmostEqual(self.votes[name]["c"] * 100, c, delta=0.0006, msg=name)
            self.assertAlmostEqual(self.votes[name]["sigma"] * 100, sigma, delta=0.0006, msg=name)
        self.assertAlmostEqual(self.anchor["v"] * PCT, 0.0975, places=4)
        self.assertAlmostEqual(self.anchor["sv"] * PCT, 0.024, places=3)

    def test_outlier_is_the_hourly(self):
        outlier, z, _, _ = votes.find_outlier(list(self.votes.values()), self.anchor)
        self.assertEqual(outlier["name"], "1h")
        self.assertAlmostEqual(z["1h"], 4.8, places=1)

    def test_range_trade(self):
        s = votes.signal(LEGS, SD, NU)
        self.assertEqual((s["kind"], s["outlier"], s["lo"], s["hi"], s["side"]), ("outlier", "1h", "15m", "1h", "buy"))
        self.assertAlmostEqual(s["market"] * 100, 2.0, places=6)
        self.assertAlmostEqual(s["model"] * 100, 4.5, delta=0.1)
        self.assertAlmostEqual(s["edge"] * 100, 2.5, delta=0.1)


class MathsTest(unittest.TestCase):
    def test_tau_eff(self):
        self.assertEqual(votes.tau_eff(240, 0), 240)
        self.assertEqual(votes.tau_eff(240, 60), 200)                 # tau - 2w/3
        self.assertAlmostEqual(votes.tau_eff(60, 60), 20)             # both branches meet at w/3
        self.assertAlmostEqual(votes.tau_eff(60.0001, 60), 20, places=3)
        self.assertAlmostEqual(votes.tau_eff(30, 60), 30 ** 3 / (3 * 3600))
        self.assertEqual(votes.tau_eff(0, 60), 0)

    def test_legs_that_cannot_vote(self):
        self.assertIsNone(votes.leg_vote(leg("5m", 99_950, 0.99, 0), NU))            # outside the band
        self.assertIsNone(votes.leg_vote(leg("5m", 99_950, 0.40, 0), NU))            # spot above line, price below 0.5
        self.assertIsNone(votes.leg_vote(leg("5m", float("nan"), 0.40, 0), NU))      # line not known
        one_sided = dict(leg("5m", 99_950, 0.62, 0), bid=float("nan"))
        self.assertIsNone(votes.leg_vote(one_sided, NU))

    def test_consistent_legs_give_no_signal(self):
        # prices generated by the model itself at one width must not raise a signal
        width = 0.001
        legs = []
        for name, line in (("5m", 99_950), ("15m", 100_100), ("1h", 100_150)):
            p = float(votes.stats.t.sf(math.log(line / 100_000) / width, NU))
            legs.append(leg(name, line, p, 0))
        s = votes.signal(legs, width / math.sqrt(TAU) / math.sqrt((NU - 2) / NU), NU)
        self.assertEqual((s["kind"], s["n_votes"]), ("none", 3))
        self.assertAlmostEqual(s["consensus"] * math.sqrt(TAU), width, places=6)

    def test_two_legs(self):
        agree = votes.signal(LEGS[:1] + [leg("15m", 100_200, 0.20, 15)], SD, NU)
        self.assertEqual(agree["kind"], "none")
        s = votes.signal(LEGS[1:], SD, NU)                # 15m and 1h disagree, no leg is named
        self.assertEqual((s["kind"], s["outlier"], s["lo"], s["hi"]), ("pair", None, "15m", "1h"))
        # believing the 15m the range is worth 4.3 cents, believing the 1h 10.1 cents; the market asks 2.
        # Both say buy, and the smaller edge counts.
        self.assertEqual(s["side"], "buy")
        self.assertAlmostEqual(s["edge"] * 100, 2.35, delta=0.1)
        # the same two legs with a wide spread: the edge is gone, so no trade
        wide = [dict(l, bid=l["bid"] - 0.01, ask=l["ask"] + 0.02) for l in LEGS[1:]]
        self.assertIsNone(votes.signal(wide, SD, NU)["side"])

    def test_one_leg_is_no_signal(self):
        self.assertEqual(votes.signal(LEGS[:1], SD, NU)["kind"], "none")

    def test_nu_for(self):
        nu = {5: 4.0, 15: 3.5, 60: 3.0}
        self.assertEqual([votes.nu_for(t, nu) for t in (10, 300, 301, 900, 3000, 9999)], [4.0, 4.0, 3.5, 3.5, 3.0, 3.0])


if __name__ == "__main__":
    unittest.main()
